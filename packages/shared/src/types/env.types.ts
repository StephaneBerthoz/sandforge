/**
 * An environment as code — the shapes of `sandforge.yaml`, of what SandForge
 * keeps of one environment applied to one org, of what applying it would do,
 * and of how each step ended.
 *
 * The file describes, in a project's repository, the data an environment
 * needs; the target org is always named on the command line, never in the
 * file. Each resource is applied, refreshed and taken back by the script that
 * already does it, so the environment adds no write path of its own: it adds
 * a declared file, a state, a plan and an order.
 *
 * Every shape here is pinned to its zod schema (`schemas/env.schema.ts`) by
 * the types' test: the state is parsed on every read and a file that does not
 * parse is refused, never guessed, so a field one side holds and the other
 * does not would make a state its own writer cannot read back.
 */

import type { ForgeTemplateInput } from '../schemas/forge.schema.js';
import type { ForgeDepth } from './forge.types.js';
import type { FieldRule, SeedRelation, SeedTemplate } from './seed.types.js';

// ─── The file (sandforge.yaml, version 1) ───────────────────────────────────

/** `{ env: NAME }`: a value read from the process environment, by name. */
export interface EnvRef {
  env: string;
}

/** The kinds of org an environment may be applied to: never a production org. */
export type EnvTargetKind = 'scratch' | 'developer' | 'sandbox';

/** Which orgs an apply may write to. */
export interface EnvTargets {
  /** Scratch orgs and Developer Edition orgs unless the file says otherwise. */
  kinds: EnvTargetKind[];
  /**
   * Organization Ids of the sandboxes an apply may write to: nothing
   * Salesforce says tells a full copy from a developer sandbox, so each one
   * is listed, and a refresh, which changes the Id, takes it off the list.
   */
  sandboxes: string[];
  /** Organization Ids refused whatever else says. */
  protect: string[];
}

/** An org a resource names by its role: an alias, or the variable holding one. */
export interface EnvOrgRole {
  alias: string | EnvRef;
}

/** The checkpoints of the environment's lifecycle. */
export interface EnvCheckpointSettings {
  /** Take one before the first write; `destroy --rewind` returns to it. */
  before?: boolean;
  /** Take one, under this name, once applied; `reset` rewinds to it. */
  after?: false | string;
  /** Fields the checkpoints do not compare, as `Case.Last_Touched__c`. */
  ignoreFields?: string[];
}

/** Acceptances a resource carries, reviewed in the file: CI has nobody to ask. */
export interface EnvAccept {
  /** Apply although the org runs automation as the records go in. */
  automation?: boolean;
}

/** A forge resource's acceptances: those of every resource, and real data. */
export interface EnvForgeAccept extends EnvAccept {
  /**
   * Clone from a production source without anonymizing what is cloned:
   * real people's data written into the org to fill, reviewed in the file.
   */
  realData?: boolean;
}

/** An object a seed resource writes. */
export interface EnvSeedObject {
  object: string;
  count: number;
  /** Seed's field rules, as the panel saves them. */
  fields?: FieldRule[];
  /** Record types by DeveloperName; several take turns at random. */
  recordTypes?: string[];
  batchSize?: number;
}

/**
 * Where a relation's parents come from: the records the resource writes of
 * `object`; with `existing`, records the org already holds; with `from`, the
 * records another resource of the file created, by their ids.
 */
export interface EnvSeedParents {
  /** The parent object; `from` may name it instead, as `accounts.Account`. */
  object?: string;
  existing?: {
    /** A SOQL WHERE condition, without the keyword. */
    where?: string;
    limit: number;
  };
  /** Another resource of the file, or a resource and an object: `accounts`, `accounts.Account`. */
  from?: string;
  /** With `from`: the most of those records drawn, the first created first. */
  limit?: number;
}

/** How many children each parent receives, as Seed's relations say it. */
export type EnvSeedDistribution =
  | { mode: 'perParent'; count: number }
  | { mode: 'range'; min: number; max: number }
  | { mode: 'ratio'; ratio: number };

/** A lookup of an object the resource writes, filled from parent records. */
export interface EnvSeedRelation {
  /** The lookup, named with its object: `Contact.AccountId`. */
  lookup: string;
  parents: EnvSeedParents;
  distribution: EnvSeedDistribution;
}

/** Records generated by Seed: a built-in template, or objects with counts, rules and relations. */
export interface EnvSeedResource {
  kind: 'seed';
  dependsOn?: string[];
  accept?: EnvAccept;
  /** A built-in template's id. */
  template?: string;
  objects?: EnvSeedObject[];
  relations?: EnvSeedRelation[];
  /** The locale the names, addresses and phone numbers are drawn in, as `fr_FR`. */
  locale?: string;
  /** The draws; recorded in the state when left out. */
  seed?: number;
}

/**
 * The record a forge resource clones: by its id, or by its object and a
 * condition its source answers with exactly one row, read at each plan.
 */
export interface EnvForgeRecord {
  id?: string;
  object?: string;
  /** A SOQL condition, without the keyword. */
  where?: string;
}

/** A table a forge resource clones whole, under its condition. */
export interface EnvForgeTable {
  object: string;
  /** A SOQL condition, without the keyword; every row when absent. */
  where?: string;
}

/** An entry of a Forge templates file, by its id. */
export interface EnvForgeTemplateRef {
  /** From the folder of the file, as `.sandforge/forge-templates.json`. */
  file: string;
  id: string;
}

/** Forge's anonymization, as a template holds it. */
export interface EnvForgeAnonymize {
  presetId?: string;
  rules: NonNullable<ForgeTemplateInput['anonymization']>['rules'];
  fields?: Array<{ objectApiName: string; fieldNames: string[] }>;
}

/** Records cloned by Forge from an org the file names by its role: one record and its graph, or whole tables. */
export interface EnvForgeResource {
  kind: 'forge';
  dependsOn?: string[];
  accept?: EnvForgeAccept;
  /** The org role it clones from: a key of the file's orgs. */
  source: string;
  record?: EnvForgeRecord;
  tables?: EnvForgeTable[];
  template?: EnvForgeTemplateRef;
  depth?: ForgeDepth;
  customDepth?: number;
  maxNodes?: number;
  anonymize?: EnvForgeAnonymize;
  keepContactPoints?: boolean;
  /** The most records a run of it may write. */
  maxTotal?: number;
}

/** The dataset a frozen resource loads, pinned: a path outside the repository, its version and its digest. */
export interface EnvFrozenDataset {
  /** From the root, or the variable that holds it. */
  path: string | EnvRef;
  /** Its manifest's version. */
  version: string;
  /** `sha256:` and 64 hexadecimal digits, over the files a load reads. */
  digest: string;
}

/** A Frozen Dataset a person froze beforehand, loaded by `sandforge-frozen`. */
export interface EnvFrozenResource {
  kind: 'frozen';
  dependsOn?: string[];
  accept?: EnvAccept;
  /** The Frozen configuration, from the folder of the file: committed, it holds no record. */
  config: string;
  dataset: EnvFrozenDataset;
}

/** A resource of the file. Version 1 holds the `seed`, `forge` and `frozen` kinds. */
export type EnvResource = EnvSeedResource | EnvForgeResource | EnvFrozenResource;

/** `sandforge.yaml`, version 1, as read: defaults in place, variables as written. */
export interface EnvFile {
  version: 1;
  name: string;
  description?: string;
  targets: EnvTargets;
  orgs: Record<string, EnvOrgRole>;
  checkpoint?: EnvCheckpointSettings;
  resources: Record<string, EnvResource>;
}

/**
 * What a seed resource runs: the template `sandforge-seed` is given as a file,
 * converted from the resource and checked by Seed's own payload schema, and
 * the flags given beside it.
 */
export interface EnvSeedRun {
  /** The template, but for the relations whose parents another resource created: see `draws`. */
  template: SeedTemplate;
  locale?: string;
  seed?: number;
  /** Record types by object, by DeveloperName. */
  recordTypes?: Record<string, string[]>;
  acceptAutomation: boolean;
  /**
   * The relations whose parents are the records another resource created,
   * handed to the seed by their ids once that resource has run: what the
   * template is given before each dry run and each run.
   */
  draws?: EnvSeedDraw[];
}

/** A relation of a seed resource whose parents another resource of the file created. */
export interface EnvSeedDraw {
  /** Its place among the resource's relations, as the file lists them. */
  at: number;
  /** The relation, all but its parents. */
  relation: Omit<SeedRelation, 'parents'>;
  /** The resource whose records the parents are. */
  from: string;
  /** The most of those records drawn, the first created first; at most 2,000 in any case. */
  limit?: number;
}

/**
 * What a frozen resource loads: the committed configuration, checked by
 * Frozen's own schema, which the environment gives the folders it keeps the
 * loads in and the dataset is read from; and the dataset, pinned.
 */
export interface EnvFrozenRun {
  /** The configuration's file, from the folder of the file. */
  configFile: string;
  /** What it holds, checked; without `sasDir` and `datasetDir`, which the environment sets. */
  config: Record<string, unknown>;
  dataset: EnvFrozenDataset;
}

/**
 * What a forge resource runs: the template `sandforge-clone` is given as a
 * file, exported from the resource and checked by Forge's own template
 * schema, and what it clones, which the line names beside it.
 */
export interface EnvForgeRun {
  /** The org role it clones from. */
  source: string;
  template: ForgeTemplateInput;
  /** One record, by its id or by the query read at each plan; or the tables. */
  record?: EnvForgeRecord;
  tables?: EnvForgeTable[];
  /** The most records a run may write, the file's; the plan's count holds it lower. */
  maxTotal?: number;
  acceptAutomation: boolean;
  /** A production source cloned without anonymization: accepted in the file. */
  acceptRealData: boolean;
}

// ─── The state (state.json, version 1) ──────────────────────────────────────

export type EnvResourceKind = 'seed' | 'forge' | 'frozen' | 'mask';

/** The script that applies, refreshes and destroys each kind of resource. */
export type EnvScript =
  'sandforge-seed' | 'sandforge-clone' | 'sandforge-frozen' | 'sandforge-dataops';

/**
 * Where a resource stands. `applying` and `destroying` are written before the
 * script is started, so a process killed anywhere leaves a state that names
 * the run, and the run's own file names what it wrote.
 */
export type EnvResourceStatus =
  'applying' | 'applied' | 'partial' | 'failed' | 'destroying' | 'destroyed';

/** What a run created of one object, and what the org refused. */
export interface EnvRunObject {
  objectApiName: string;
  created: number;
  refused: number;
}

/** One run of a resource's script, pointing at what the run itself keeps. */
export interface EnvRun {
  /** The run's rank among its resource's runs, from 1. */
  n: number;
  script: EnvScript;
  /** Seed's run id, given by the environment. */
  runId?: string;
  /** `runs/<resource>/<n>.summary.json`, from the state's folder. */
  summary?: string;
  /** `frozen/<resource>`, from the state's folder. */
  sas?: string;
  /** A mask's DataOps snapshot. */
  snapshotId?: string;
  /** A seed's draws. */
  seed?: number;
  /** On the org's clock. */
  startedAt: string;
  endedAt?: string;
  exitCode?: number;
  objects: EnvRunObject[];
  /** Taken back whole by a removal: a later removal of the resource skips it. */
  takenBack?: true;
}

/** What the state keeps of one resource. */
export interface EnvResourceState {
  kind: EnvResourceKind;
  /** The canonical fingerprint it was applied from. */
  fingerprint: string;
  dependsOn: string[];
  status: EnvResourceStatus;
  /** The last is current; earlier ones are runs a replace took back. */
  runs: EnvRun[];
}

/**
 * One environment applied to one org: ids, counts and dates, never a
 * record's values, so it may be cached as the scripts' run files are.
 */
export interface EnvState {
  version: 1;
  /** The file's name. */
  env: string;
  /** Set at the first apply: a state found under another org, or made again, is told apart. */
  lineage: string;
  /** One more on every write: a plan names the serial it was made against. */
  serial: number;
  sandforgeVersion: string;
  /** When the state was last written, by this machine's clock. */
  updatedAt: string;
  org: { organizationId: string; kind: EnvTargetKind; username: string; alias?: string };
  /** The resolved, canonical file it was last applied from. */
  file: { digest: string };
  /** Checkpoint ids in the shared store. */
  checkpoints?: { before?: string; after?: string };
  resources: Record<string, EnvResourceState>;
}

// ─── The plan ────────────────────────────────────────────────────────────────

/**
 * What applying does to a resource: runs it (`create`), nothing (`keep`, and
 * `drifted` unless asked), takes its runs back and runs it again
 * (`replace`), takes them back (`delete`), or refuses the whole apply before
 * its first write (`blocked`).
 */
export type EnvActionKind = 'create' | 'keep' | 'replace' | 'delete' | 'drifted' | 'blocked';

/** Which of an org's daily email limits a count is held to. */
export type EnvEmailLimit = 'SingleEmail' | 'DailyWorkflowEmails';

/** One object of a planned action. */
export interface EnvPlanObject {
  object: string;
  /** Records a create or a replace would write: its dry run's count. */
  wouldCreate?: number;
  /**
   * `wouldCreate` is the most it writes, not its count: its records hang from
   * records a resource that runs first in the same apply writes, which its
   * dry run could not read.
   */
  atMost?: true;
  /** Records of an earlier apply the org still holds as written. */
  present?: number;
  /** Records of an earlier apply deleted since. */
  gone?: number;
  /** Records of an earlier apply someone changed since. */
  changed?: number;
}

/** What one action takes of the org's day. */
export interface EnvActionGates {
  apiRequests?: number;
  storageBytes?: number;
  emails?: Array<{ limit: EnvEmailLimit; emails: number }>;
}

/**
 * A relation whose parents are the records another resource created: how many
 * there are, once that resource has run; absent while it runs in the same
 * apply, before which nobody knows.
 */
export interface EnvActionDraw {
  /** The lookup, named with its object: `Contact.AccountId`. */
  lookup: string;
  from: string;
  object: string;
  parents?: number;
}

/** One resource's line of a plan. */
export interface EnvAction {
  resource: string;
  kind: EnvResourceKind;
  action: EnvActionKind;
  why: string;
  objects: EnvPlanObject[];
  /** The relations whose parents another resource created. */
  draws?: EnvActionDraw[];
  gates?: EnvActionGates;
  refusal?: string;
  /** What the plan says of it beside why: a production source's data, and what is done to it. */
  notes?: string[];
}

/** A checkpoint of the environment's lifecycle: taken before the first write, or once applied. */
export type EnvCheckpointStep = 'before' | 'after';

/** A refusal the checkpoint script gives, in its own code and words. */
export interface EnvCheckpointRefusal {
  code: string;
  message: string;
}

/**
 * A checkpoint an apply takes, as its plan says it: under which name, what
 * the checkpoint script estimates it costs, and what refuses it now — which
 * refuses the apply before its first write.
 */
export interface EnvPlanCheckpoint {
  step: EnvCheckpointStep;
  name: string;
  /** The checkpoint script's own estimate of the take. */
  estimate?: { records: number; apiRequests: number; seconds: number; bytes: number };
  refusal?: EnvCheckpointRefusal;
  /** Why it was not estimated: --quick, or the script gave no answer. */
  unread?: string;
}

/**
 * The whole org against the checkpoint taken after the last apply, as the
 * checkpoint script's own preview reads it.
 */
export interface EnvPlanDrift {
  checkpoint: string;
  /** The org differs from it among the objects and fields it compares. */
  differs: boolean;
  /** What a rewind to it would do now. */
  toDelete?: number;
  toGiveBack?: number;
  toBringBack?: number;
  /** Why the org could not be compared with it: never taken for one that does not differ. */
  unread?: string;
}

/**
 * The day's budget, summed across the resources a plan writes. What the org
 * has left is absent when its `/limits` did not say, and `unread` says why.
 */
export interface EnvPlanGates {
  apiRequests: {
    estimate: number;
    leftToday?: number;
    /** A script whose dry run gives no estimate leaves the sum short of the truth. */
    partial: boolean;
    /** What the sum leaves out, each named: a dry run not run, a removal's requests. */
    notCounted?: string[];
    unread?: string;
  };
  storage: { bytes: number; left?: number; unread?: string };
  emails: Array<{ limit: EnvEmailLimit; emails: number; left?: number }>;
}

/** What applying the file to an org would do; writes nothing, to the org or the state. */
export interface EnvPlan {
  env: string;
  org: { organizationId: string; kind: EnvTargetKind; alias?: string };
  state: { found: boolean; serial?: number };
  /** In the order apply runs them. */
  actions: EnvAction[];
  totals: {
    create: number;
    keep: number;
    replace: number;
    delete: number;
    drifted: number;
    blocked: number;
  };
  gates: EnvPlanGates;
  /** The checkpoints an apply takes, in the order it takes them. */
  checkpoints?: EnvPlanCheckpoint[];
  /** The whole org against the checkpoint taken after the last apply. */
  drift?: EnvPlanDrift;
  /** What a real apply would meet now. */
  refusal?: string;
  /** Made with `--quick`: no dry run, no removal preview, so no count of what the org holds. */
  quick?: true;
  /** What the plan says without refusing: an apply under way, a scratch org with no state. */
  warnings?: string[];
}

// ─── How each step ended ─────────────────────────────────────────────────────

/** A step runs a resource's script, or takes a run of it back. */
export type EnvStepPhase = 'run' | 'remove';

/** One object of a step, as the script answered. */
export interface EnvStepObject {
  object: string;
  created: number;
  refused: number;
  deleted: number;
  kept: number;
  reason?: string;
}

/** One spawned script, and how it ended. */
export interface EnvStepResult {
  resource: string;
  /** The plan's action the step serves. */
  action: EnvActionKind;
  phase: EnvStepPhase;
  /** The rank of the run the step ran, or took back. */
  run: number;
  script: EnvScript;
  exitCode: number;
  /** The resource's status once the step ended. */
  status: EnvResourceStatus;
  summary?: string;
  objects: EnvStepObject[];
  /** The script's own `--json` answer, as it gave it. */
  answer?: unknown;
}

/**
 * A checkpoint step of an apply or a destroy, and how the checkpoint script
 * ended it: a take before the first write or once applied, or the deletion
 * of one the environment no longer needs.
 */
export interface EnvCheckpointStepResult {
  step: EnvCheckpointStep | 'delete';
  /** The checkpoint taken, or deleted. */
  checkpoint?: string;
  exitCode: number;
  /** What refused or failed it, in the checkpoint script's words. */
  refusal?: string;
  /** The checkpoint script's own `--json` answer, as it gave it. */
  answer?: unknown;
}

/** What `apply` and `destroy` answer with `--json`. */
export interface EnvRunResult {
  plan: EnvPlan;
  steps: EnvStepResult[];
  /** The checkpoints taken and deleted, in order. */
  checkpoints?: EnvCheckpointStepResult[];
  /** Resources no step ran for, each with why: a dependency left partial, a stop before them. */
  skipped?: Array<{ resource: string; why: string }>;
  status: 'success' | 'partial' | 'failure' | 'cancelled';
  /** Why nothing was done, when it was refused before its first step. */
  refusal?: string;
  /** The state as the run left it: a destroy that took everything back keeps it, every resource destroyed. */
  state: { serial: number };
}

/**
 * Whether the checkpoint script offers to undo a rewind, as it offers it:
 * until when, and the line that does; or why it does not.
 */
export type EnvRewindUndo =
  { offered: true; until: string; line: string } | { offered: false; why: string };

/**
 * What `reset` and `destroy --rewind` answer with `--json`: the org rewound
 * to a checkpoint of the environment by the checkpoint script, what its own
 * preview counted before, how it ended, and whether it can be undone.
 */
export interface EnvRewindResult {
  env: string;
  org: { organizationId: string; kind: EnvTargetKind; alias?: string };
  /** `reset`, to the checkpoint taken after the last apply; `destroy`, to the one taken before the first. */
  verb: 'reset' | 'destroy';
  checkpoint: { step: EnvCheckpointStep; id: string; name?: string; takenAt?: string };
  /** What the rewind's preview counted before the question, and who last changed it. */
  preview?: {
    toDelete: number;
    toGiveBack: number;
    toBringBack: number;
    /** By the name of each user, the records to delete or give back they last changed. */
    lastChangedBy: Record<string, number>;
  };
  /** The rewind's own exit code: 0, 1, 3, 4, or a stop's. */
  exitCode: number;
  status: 'success' | 'partial' | 'unstable' | 'failure' | 'cancelled';
  /** The checkpoint script's own `--json` answer, as it gave it. */
  answer?: unknown;
  undo: EnvRewindUndo;
  /** Why nothing was rewound, when it was refused before the rewind. */
  refusal?: string;
  /** The checkpoints deleted once the environment was taken back: destroy --rewind's. */
  deleted?: EnvCheckpointStepResult[];
  state: { serial: number };
}

// ─── What the other verbs answer ─────────────────────────────────────────────

/** One refusal or warning of the file, where it stands. */
export interface EnvIssue {
  /** Where in the file, as a line names it: `resources.accounts.objects[0].count`. */
  path: string;
  resource?: string;
  message: string;
}

/** What a verb refused before it read or wrote anything, as `--json` answers it. */
export interface EnvRefusalAnswer {
  refusal: {
    /** What refused, in a word a pipeline reads: PRODUCTION, NOT_LISTED, LOCKED… */
    code: string;
    message: string;
    /** The file's refusals, each where it stands. */
    issues?: EnvIssue[];
  };
}

/** What `validate --json` answers: the file checked offline, or why it is not valid. */
export interface EnvValidation {
  file: string;
  valid: boolean;
  /** Present when valid. */
  env?: string;
  /** In the order apply runs them. */
  resources?: Array<{
    name: string;
    kind: EnvResourceKind;
    dependsOn: string[];
    /** The org role a forge resource clones from. */
    source?: string;
    /** The objects it writes; a forge resource's are counted by its dry run alone. */
    objects: Array<{ object: string; count?: number }>;
  }>;
  /** The variables the file reads, and whether this process has each set. */
  variables?: Array<{
    name: string;
    /** The org role whose alias it holds. */
    role?: string;
    /** The frozen resource whose dataset's path it holds. */
    resource?: string;
    set: boolean;
  }>;
  issues: EnvIssue[];
  warnings: EnvIssue[];
}

/** One state kept on this machine, as `state --json` lists it. */
export interface EnvStateListEntry {
  env: string;
  organizationId: string;
  alias?: string;
  kind?: EnvTargetKind;
  serial?: number;
  resources?: Record<string, EnvResourceStatus>;
  updatedAt?: string;
  expiresAt?: string;
  /** Why the state is not used: it does not parse, or names another org. */
  damaged?: string;
}

/** What `state --json` answers: the states kept on this machine, and those it deleted on their date. */
export interface EnvStateList {
  journalDir: string;
  states: EnvStateListEntry[];
  expired: Array<{ env: string; organizationId: string; alias?: string; expiresAt: string }>;
}
